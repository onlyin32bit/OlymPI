package opsocket

import (
	"fmt"
	"io"
	"reflect"
	"sort"
	"strings"
	"unicode"
)

type TypeScriptSchema struct {
	Events  map[string]any
	Aliases map[string]any
	Enums   map[string][]string
}

// WriteTypeScript generates the browser operation contract from the same
// reflected controller registry used at runtime.
func (s *Socket) WriteTypeScript(w io.Writer, schema TypeScriptSchema) error {
	aliases := make(map[reflect.Type]string, len(schema.Aliases))
	aliasNames := make([]string, 0, len(schema.Aliases))
	for name, value := range schema.Aliases {
		aliases[reflect.TypeOf(value)] = name
		aliasNames = append(aliasNames, name)
	}
	sort.Strings(aliasNames)
	renderer := tsRenderer{aliases: aliases}
	if _, err := fmt.Fprint(w, "// Code generated by go run ./cmd/gen; DO NOT EDIT.\n\n"); err != nil {
		return err
	}
	for _, name := range aliasNames {
		var typ reflect.Type
		for candidate, candidateName := range aliases {
			if candidateName == name {
				typ = candidate
				break
			}
		}
		if values := schema.Enums[name]; len(values) > 0 {
			quoted := make([]string, len(values))
			for i, value := range values {
				quoted[i] = fmt.Sprintf("'%s'", value)
			}
			fmt.Fprintf(w, "export type %s = %s;\n\n", name, strings.Join(quoted, " | "))
		} else {
			fmt.Fprintf(w, "export type %s = %s;\n\n", name, renderer.render(typ, typ))
		}
	}
	operations := make([]string, 0, len(s.controllers))
	for name := range s.controllers {
		operations = append(operations, name)
	}
	sort.Strings(operations)
	for _, operation := range operations {
		controller := s.controllers[operation]
		base := exportedName(operation)
		fmt.Fprintf(w, "export type %sRequest = %s;\n", base, renderer.render(controller.reqType, nil))
		response := "void"
		if controller.respType != nil {
			response = renderer.render(controller.respType, nil)
		}
		fmt.Fprintf(w, "export type %sResponse = %s;\n\n", base, response)
	}
	eventNames := make([]string, 0, len(schema.Events))
	for name := range schema.Events {
		eventNames = append(eventNames, name)
	}
	sort.Strings(eventNames)
	for _, event := range eventNames {
		fmt.Fprintf(w, "export type %sEvent = %s;\n", exportedName(event), renderer.render(reflect.TypeOf(schema.Events[event]), nil))
	}
	fmt.Fprint(w, "\nexport interface OpsocketOperations {\n")
	for _, operation := range operations {
		base := exportedName(operation)
		fmt.Fprintf(w, "\t'%s': { request: %sRequest; response: %sResponse };\n", operation, base, base)
	}
	fmt.Fprint(w, "}\n\nexport interface OpsocketEvents {\n")
	for _, event := range eventNames {
		fmt.Fprintf(w, "\t'%s': %sEvent;\n", event, exportedName(event))
	}
	_, err := fmt.Fprintln(w, "}")
	return err
}

type tsRenderer struct{ aliases map[reflect.Type]string }

func (r tsRenderer) render(typ, root reflect.Type) string {
	if typ == nil {
		return "void"
	}
	if typ != root {
		if name, ok := r.aliases[typ]; ok {
			return name
		}
	}
	if typ.Kind() == reflect.Pointer {
		return r.render(typ.Elem(), root) + " | null"
	}
	if typ.PkgPath() == "time" && typ.Name() == "Time" {
		return "string"
	}
	if typ.PkgPath() == "encoding/json" && typ.Name() == "RawMessage" {
		return "unknown"
	}
	switch typ.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.String:
		return "string"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Interface:
		return "unknown"
	case reflect.Slice, reflect.Array:
		return r.render(typ.Elem(), root) + "[]"
	case reflect.Map:
		return "Record<string, " + r.render(typ.Elem(), root) + ">"
	case reflect.Struct:
		fields := make([]string, 0, typ.NumField())
		embeddedTypes := make([]string, 0)
		for i := 0; i < typ.NumField(); i++ {
			field := typ.Field(i)
			if !field.IsExported() {
				continue
			}
			tag := field.Tag.Get("json")
			name, options, _ := strings.Cut(tag, ",")
			if name == "-" {
				continue
			}
			if field.Anonymous && name == "" {
				embeddedTypes = append(embeddedTypes, r.render(field.Type, root))
				continue
			}
			if name == "" {
				name = field.Name
			}
			optional := strings.Contains(options, "omitempty")
			fields = append(fields, fmt.Sprintf("%s%s: %s", name, map[bool]string{true: "?", false: ""}[optional], r.render(field.Type, root)))
		}
		object := "Record<string, never>"
		if len(fields) > 0 {
			object = "{ " + strings.Join(fields, "; ") + " }"
		}
		if len(embeddedTypes) > 0 {
			if len(fields) == 0 {
				return strings.Join(embeddedTypes, " & ")
			}
			return strings.Join(append(embeddedTypes, object), " & ")
		}
		return object
	}
	return "unknown"
}
func exportedName(value string) string {
	var result []rune
	upper := true
	for _, char := range value {
		if !unicode.IsLetter(char) && !unicode.IsDigit(char) {
			upper = true
			continue
		}
		if upper {
			char = unicode.ToUpper(char)
			upper = false
		}
		result = append(result, char)
	}
	return string(result)
}
